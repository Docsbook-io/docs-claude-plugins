#!/usr/bin/env node
/**
 * Refresh scripts/mcp-tools.json from the live Docsbook MCP server.
 *
 * check-plugin.mjs validates every `mcp__plugin_docsbook_docsbook__<tool>` named
 * in a command or agent against that file. That check is only as truthful as the
 * file, and the file was hand-maintained: it was written by reading
 * src/app/api/mcp/server/route.ts in the product repo and copying the names out.
 * By the time anyone looked again it was missing ten tools the server had gained
 * — the whole goals-and-funnels family (create_goal, get_goals, list_goals,
 * delete_goal, create_funnel, get_funnel, get_goal_journeys, get_goal_visitors,
 * mark_path_as_funnel_step) plus `search`. Nothing failed, because the checker
 * only rejects names it does not know; a tool missing from the list makes any
 * command that uses it fail the check, so the drift pushes authors AWAY from the
 * newest tools. Silent, and in the wrong direction.
 *
 * `GET /api/mcp/tools` enumerates the real server over a real MCP `tools/list`,
 * which is the same endpoint the product's own admin panel reads rather than a
 * second hand-kept copy. Fetching it is the whole job.
 *
 * Usage:
 *   node scripts/sync-mcp-tools.mjs           rewrite the file
 *   node scripts/sync-mcp-tools.mjs --check   fail if the file is stale
 *
 * --check is deliberately NOT in the pull-request CI job: it depends on a live
 * network call to docsbook.io, and a deploy in progress would turn every open PR
 * red for a reason that has nothing to do with the PR. It belongs in the
 * scheduled sync, where a refresh is a commit and an outage is just a retry an
 * hour later. What PR CI checks is the committed file's internal consistency.
 */

import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const OUT = join(REPO_ROOT, "scripts", "mcp-tools.json")
const ENDPOINT = "https://docsbook.io/api/mcp/tools"
const CHECK = process.argv.includes("--check")

const die = (msg) => { console.error(`\n✗ sync-mcp-tools: ${msg}\n`); process.exit(1) }

// curl, not fetch(): Node's fetch ignores HTTPS_PROXY, so behind a proxy the
// request fails in a shape that reads as "the server returned nothing".
let body
try {
  body = execFileSync("curl", ["-fsSL", ENDPOINT], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] })
} catch {
  die(`could not reach ${ENDPOINT}`)
}

let payload
try { payload = JSON.parse(body) } catch { die(`${ENDPOINT} did not return JSON`) }
const names = (payload.tools ?? []).map((t) => t.name).filter(Boolean).sort()
if (!names.length) die(`${ENDPOINT} listed zero tools — refusing to write an empty catalog`)

const next = {
  _comment:
    "Generated by scripts/sync-mcp-tools.mjs from the live MCP server's tools/list. Do not hand-edit — run `node scripts/sync-mcp-tools.mjs`. check-plugin.mjs validates every tool named in a command or agent against this list, which is how a command referencing a non-existent tool (register_webhook_translation_requested) gets caught before release.",
  source: ENDPOINT,
  count: names.length,
  tools: names,
}
const serialized = JSON.stringify(next, null, 2) + "\n"

if (CHECK) {
  const committed = readFileSync(OUT, "utf8")
  if (committed !== serialized) {
    const have = new Set(JSON.parse(committed).tools)
    const added = names.filter((n) => !have.has(n))
    const removed = [...have].filter((n) => !names.includes(n)).sort()
    die(
      `scripts/mcp-tools.json is stale — run \`node scripts/sync-mcp-tools.mjs\` and commit.` +
        (added.length ? `\n  + the server gained: ${added.join(", ")}` : "") +
        (removed.length ? `\n  − the server no longer registers: ${removed.join(", ")}` : ""),
    )
  }
  console.log(`✓ scripts/mcp-tools.json matches the live server (${names.length} tools)`)
} else {
  writeFileSync(OUT, serialized, "utf8")
  console.log(`✓ wrote ${names.length} tools to scripts/mcp-tools.json`)
}
